#!/usr/bin/env python3
"""Generates godot/data/levels/climb.txt: the jackpot climb (level 3 of the game, level_id 5).

Deterministic (fixed seed). The level is climbed from the bottom (floor + P) to the top (E).
Every row from the floor up has a platform reachable from the one below with ONE normal jump;
the script reads the jump physics from scripts/screens/platformer.gd and asserts it.

    python3 tools/gen_climb.py            # writes the map
    python3 tools/gen_climb.py --check    # only checks the current file
"""
import math
import random
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "godot/data/levels/climb.txt"
PLATFORMER = ROOT / "godot/scripts/screens/platformer.gd"

COLS = 36  # LevelData.CLIMB_COLS: wider than the other levels (drawn zoomed out)
ROW_H = 120.0
CELL_W = 1066.0 / 25  # the cell width of every level (LevelData.CELL_W)
ROWS = 170
SEED = 3105
PLAYER_W = 30.0
# Landing: a falling player lands when her feet were at most this far below the top (platformer.gd).
LAND_TOL = 20.0
BOB = 5.0  # platforms bob ±5 px


def const(name: str) -> float:
    m = re.search(r"const %s := (-?[0-9.]+)" % name, PLATFORMER.read_text())
    assert m, name
    return float(m.group(1))


GRAVITY = const("GRAVITY")
JUMP = -const("JUMP_FORCE")
SPEED = const("MAX_SPEED")


def rise_frames(v: float) -> list:
    """Height above the take-off after each frame, as platformer.gd steps it (gravity
    is added to vy before she moves, so this is a little lower than v² / 2g)."""
    out, y = [], 0.0
    while True:
        v -= GRAVITY
        y += v
        if y < -400:
            return out
        out.append(y)


JUMP_H = max(rise_frames(JUMP))
# A double jump at the peak of the first one (always available, refilled on landing).
DOUBLE_H = 2 * JUMP_H
# Height she must rise to land on the platform one row up (worst case bob).
NEED = ROW_H - LAND_TOL + 2 * BOB
# ROW_H is fixed by the level format, so one full jump has only ~17 % to spare; the
# double jump is the real margin (the spec's ~70 %).
assert NEED <= 0.85 * JUMP_H, "a row (%.0f px) is too high for one jump (%.0f px)" % (NEED, JUMP_H)
assert NEED <= 0.7 * DOUBLE_H, "a row (%.0f px) is too high for a double jump (%.0f px)" % (NEED, DOUBLE_H)
# Frames until she comes back down to that height, and how far she runs meanwhile.
_hs = rise_frames(JUMP)
T_LAND = max(i + 1 for i, h in enumerate(_hs) if h >= NEED)
REACH_PX = SPEED * T_LAND
# Allowed empty cells between two platforms one row apart (60 % of the reach, a safe margin).
MAX_GAP = int((0.6 * REACH_PX + PLAYER_W) // CELL_W)
assert MAX_GAP >= 2, MAX_GAP

HEADER = """# The jackpot climb (level 3 of the game, level_id 5): climbed upwards, the board rises from below.
# Generated by tools/gen_climb.py (seed {seed}); one full jump ({jh:.0f} px, reach {reach:.0f} px) reaches every next row.
# Legend: = platform  P spawn  E the top  ! spring  $ heart  : bell  ? joker  0 jackpot row  Z the wheel (mg11)  ~ updraft (no dialog letters: the power-ups' dialogs play on the board)
"""


def platforms(row: str):
    """(c0, c1) inclusive cell runs of '=' in a row."""
    out, c = [], 0
    while c < len(row):
        if row[c] == "=":
            s = c
            while c < len(row) and row[c] == "=":
                c += 1
            out.append((s, c - 1))
        else:
            c += 1
    return out


def gap(a, b) -> int:
    """Empty cells between two runs (negative / 0 = they overlap or touch)."""
    return max(a[0], b[0]) - min(a[1], b[1]) - 1


def generate() -> list:
    rng = random.Random(SEED)
    grid = [["."] * COLS for _ in range(ROWS)]

    def put(r, c, ch, force=False):
        if 0 <= c < COLS and (force or grid[r][c] == "."):
            grid[r][c] = ch
            return True
        return False

    bottom = ROWS - 1
    for c in range(COLS):
        grid[bottom][c] = "="
    grid[bottom - 1][COLS // 2] = "P"
    top_plat = 2  # the wide platform at the top, E in the row above it
    mains = {bottom: [(0, COLS - 1)]}
    # Two routes wander up side by side (each one jump from its own platform below):
    # where they drift apart she picks one, where they meet they merge and split again.
    routes = [[(COLS // 2 - 9, COLS // 2 - 4), -1], [(COLS // 2 + 3, COLS // 2 + 7), 1]]

    def step(prev, direction):
        ln = rng.randint(3, 7)
        g = rng.randint(-1, MAX_GAP)  # sideways step from the previous platform
        c0 = prev[1] + 1 + g if direction > 0 else prev[0] - 1 - g - (ln - 1)
        if c0 < 0 or c0 + ln - 1 >= COLS:
            direction = -direction
            c0 = prev[1] + 1 + g if direction > 0 else prev[0] - 1 - g - (ln - 1)
        c0 = max(0, min(COLS - ln, c0))
        if rng.random() < 0.18:
            direction = -direction
        return (c0, c0 + ln - 1), direction

    for r in range(bottom - 1, top_plat, -1):
        runs = []
        for rt in routes:
            if r == bottom - 1:
                cur = rt[0]  # beside P, both sides
            else:
                cur, rt[1] = step(rt[0], rt[1])
            rt[0] = cur
            runs.append(cur)
        a, b = routes[0][0], routes[1][0]
        if gap(a, b) < 2:
            # Met: one platform (the union); split again, the left one going left.
            u = (min(a[0], b[0]), max(a[1], b[1]))
            routes[0][0] = routes[1][0] = u
            routes[0][1], routes[1][1] = -1, 1
            runs = [u]
        elif a[0] > b[0]:
            routes.reverse()
        for cur in runs:
            for c in range(cur[0], cur[1] + 1):
                put(r, c, "=", force=True)
        mains[r] = runs
        # Side branches: a short ledge off a route (hearts on it), one jump from below.
        if rng.random() < 0.35:
            below = rng.choice(mains[r + 1])
            ln2 = rng.randint(2, 4)
            if rng.random() < 0.5:
                a0 = below[0] - 1 - rng.randint(0, MAX_GAP - 1) - (ln2 - 1)
            else:
                a0 = below[1] + 1 + rng.randint(0, MAX_GAP - 1)
            a0 = max(0, min(COLS - ln2, a0))
            alt = (a0, a0 + ln2 - 1)
            if all(gap(alt, cur) >= 2 for cur in runs):
                for c in range(alt[0], alt[1] + 1):
                    put(r, c, "=")
                if rng.random() < 0.7 and r - 1 > top_plat:
                    for c in range(alt[0], alt[1] + 1):
                        put(r - 1, c, "$")
    for c in range(8, 28):
        grid[top_plat][c] = "="
    mains[top_plat] = [(8, 27)]
    grid[1][COLS // 2] = "E"

    def free_over(r):
        """Free cells of row r standing on the main platform of row r + 1."""
        return [c for b in mains.get(r + 1, []) for c in range(b[0], b[1] + 1) if grid[r][c] == "."]

    # Jackpot rows at 1/4, 2/4, 3/4 of the height (a free cell of the row; the trigger spans it).
    span = bottom - top_plat
    jackpots = [bottom - span * k // 4 for k in (1, 2, 3)]
    for r in jackpots:
        c = next(c for c in [0, COLS - 1] + list(range(COLS)) if grid[r][c] == ".")
        put(r, c, "0")

    # The wheel of the cycle (minigame mg11): once, halfway between the 1st and 2nd jackpot rows.
    wr = (jackpots[0] + jackpots[1]) // 2
    c = next(c for c in [COLS - 1, 0] + list(range(COLS)) if grid[wr][c] == ".")
    put(wr, c, "Z")

    # Springs every 8–12 rows, jokers every 18–25 rows (standing on the platform below).
    springs, slots = [], []
    r = bottom - 6
    while r > top_plat + 6:
        cells = free_over(r)
        if cells:
            c = rng.choice(cells)
            put(r, c, "!")
            springs.append((r, c))
            # Hearts up the spring's path, a fan two cells wide.
            for k in range(1, 6):
                put(r - k, c, "$")
                if k >= 3:
                    put(r - k, c + (1 if k % 2 else -1), "$")
            r -= rng.randint(8, 12)
        else:
            r -= 1
    r = bottom - 12
    while r > top_plat + 8:
        cells = [c for c in free_over(r) if grid[r - 1][c] != "!"]
        if cells:
            c = rng.choice(cells)
            put(r, c, "?")
            slots.append((r, c))
            r -= rng.randint(18, 25)
        else:
            r -= 1
    # Bells now and then (every 12–18 rows, over a platform, off the springs' paths).
    r = bottom - 9
    while r > top_plat + 6:
        cells = [c for c in free_over(r) if grid[r - 1][c] != "!" and grid[r + 1][c] != "!"]
        if cells:
            put(r, rng.choice(cells), ":")
            r -= rng.randint(12, 18)
        else:
            r -= 1
    # Hearts: little arcs over most platforms.
    for r in range(bottom - 2, top_plat, -1):
        if rng.random() < 0.55:
            cells = free_over(r)
            if len(cells) >= 2:
                start = rng.randrange(0, len(cells))
                for c in cells[start::2][:3]:
                    put(r, c, "$")
    # Updrafts: a few columns of warm air beside the path.
    r = bottom - 20
    while r > top_plat + 10:
        c = 0 if min(m[0] for m in mains[r]) > 2 else COLS - 1
        if all(grid[r - k][c] == "." for k in range(4)):
            for k in range(4):
                put(r - k, c, "~")
            r -= rng.randint(25, 35)
        else:
            r -= 1
    return ["".join(row) for row in grid]


def check(rows: list) -> dict:
    assert all(len(r) == COLS for r in rows), "rows must have %d columns" % COLS
    n = len(rows)
    text = "".join(rows)
    assert text.count("P") == 1 and text.count("E") == 1, "one spawn, one top"
    p_row = next(i for i, r in enumerate(rows) if "P" in r)
    e_row = next(i for i, r in enumerate(rows) if "E" in r)
    assert p_row >= n - 3, "the spawn is at the bottom"
    assert e_row <= 3, "the top is at the top"
    assert sum(1 for r in rows if "0" in r) == 3, "three jackpot rows"
    # The wheel of the cycle: one row, between the 1st and 2nd jackpot rows (from the bottom).
    assert text.count("Z") == 1, "one wheel (Z)"
    jrows = sorted((i for i, r in enumerate(rows) if "0" in r), reverse=True)
    z_row = next(i for i, r in enumerate(rows) if "Z" in r)
    assert jrows[1] < z_row < jrows[0], "the wheel is between the 1st and 2nd jackpot rows"
    assert not any(ch in text for ch in "^SFJCLN"), "no hazards in the climb"
    for ch in "!$:?~":
        assert ch in text, "missing " + ch
    # No dialog letters (the dialogs play on the board when a power-up is won) and no
    # minigames: the climb is never interrupted.
    assert not any(ch.islower() for ch in text), "no dialog letters in the climb"
    assert not any(ch in text for ch in "23456789"), "no minigame / boss / wave triggers in the climb"
    # Entities that stand on the platform below them.
    for i, r in enumerate(rows[:-1]):
        for c, ch in enumerate(r):
            if ch in "!?":
                assert rows[i + 1][c] == "=", "%s at row %d col %d has no platform under it" % (ch, i, c)
    # Reachability: from the floor, one jump up per row (one row up, at most MAX_GAP empty
    # cells sideways), or walking along the same row (touching runs).
    plats = {i: platforms(r) for i, r in enumerate(rows)}
    start = (n - 1, plats[n - 1][0])
    seen = {start}
    todo = [start]
    while todo:
        i, a = todo.pop()
        for j in (i - 1,):
            for b in plats.get(j, []):
                if gap(a, b) <= MAX_GAP and (j, b) not in seen:
                    seen.add((j, b))
                    todo.append((j, b))
    top = plats[e_row + 1]
    assert any((e_row + 1, b) in seen for b in top), "the top platform is not reachable"
    # Every row between the floor and the top has a reachable platform (no double jump needed).
    for i in range(e_row + 1, n):
        assert any((i, b) in seen for b in plats[i]), "row %d has no reachable platform" % i
    return {"rows": n, "springs": text.count("!"), "hearts": text.count("$"), "bells": text.count(":"), "jokers": text.count("?"),
            "updrafts": text.count("~"), "reached": len(seen), "platforms": sum(len(v) for v in plats.values())}


def main() -> None:
    if "--check" in sys.argv:
        rows = [l for l in OUT.read_text().splitlines() if l and not l.startswith("# ")]
        print(check(rows))
        return
    rows = generate()
    info = check(rows)
    OUT.write_text(HEADER.format(seed=SEED, jh=JUMP_H, reach=REACH_PX) + "\n".join(rows) + "\n")
    print("wrote %s: %s; jump %.1f px (double %.0f), row needs %.0f px (%.0f %% / %.0f %%), max gap %d cells" % (
        OUT.relative_to(ROOT), info, JUMP_H, DOUBLE_H, NEED, 100 * NEED / JUMP_H, 100 * NEED / DOUBLE_H, MAX_GAP))


if __name__ == "__main__":
    main()
